"""Generate the local MCP reference and the guide's tool map from source AST without
importing Blender."""

import argparse
import ast
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- tools:start -->", "<!-- tools:end -->"
MAP_START, MAP_END = "<!-- tool-map:start -->", "<!-- tool-map:end -->"
# The guide shows the same map again in What it does.
INTRO_START, INTRO_END = "<!-- tool-map-intro:start -->", "<!-- tool-map-intro:end -->"
GROUPS = (
    ("Scene tools (run on Blender's main thread)", "scenario/mcp/tools_blender.py"),
    ("Scenario tools", "scenario/mcp/tools_scenario.py"),
)
# Tool map families in display order: key, title, summary and the name pattern that
# claims a Scenario tool. Every scene tool is Scene and every unclaimed Scenario tool
# is Generate & place. Patterns are tried from the last family back, so Film keeps
# bind_film_upload and Jobs keeps recover_reference_upload.
FAMILIES = (
    ("scene", "Scene", "Read, select, frame, capture, render, run Python.", None),
    (
        "generate",
        "Generate & place",
        "Models, prices, generation, waits, previews, placement.",
        None,
    ),
    (
        "library",
        "Library & uploads",
        "Your Scenario assets and reference uploads.",
        r"asset|collection|reference_upload|upload_reference",
    ),
    ("workflows", "Workflows", "Run Scenario workflows step by step.", r"workflow"),
    (
        "jobs",
        "Jobs & recovery",
        "Pick up jobs after a crash or restart.",
        r"^recover_|_local_job|prepared_job",
    ),
    ("blockout", "Blockout", "Prompt to grey layout, priced and approved.", r"blockout"),
    ("film", "Film", "Shots, timeline, capture, composition, review, export.", r"film"),
)
EXPERIMENTAL = {"film"}


def _value(node):
    try:
        return ast.literal_eval(node)
    except (ValueError, TypeError):
        return ast.unparse(node)


def _properties(node, assignments):
    if not isinstance(node, ast.Dict):
        raise ValueError("Tool properties must be a dictionary")
    result = {}
    for key, value in zip(node.keys, node.values, strict=True):
        if key is None:
            if not isinstance(value, ast.Name) or value.id not in assignments:
                raise ValueError("Only named literal property fragments are supported")
            # Shared fragments themselves must be literal dictionaries; no execution.
            fragment = ast.literal_eval(assignments[value.id])
            if not isinstance(fragment, dict):
                raise ValueError("Tool property fragments must be dictionaries")
            result.update(fragment)
        else:
            if not isinstance(value, ast.Dict):
                raise ValueError("Each tool property must have a dictionary schema")
            result[ast.literal_eval(key)] = {
                ast.literal_eval(k): _value(v)
                for k, v in zip(value.keys, value.values, strict=True)
            }
    return result


def parse_specs(path):
    tree = ast.parse(Path(path).read_text(encoding="utf-8"))
    assignments = {
        node.targets[0].id: node.value
        for node in tree.body
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
    }
    specs = assignments.get("SPECS")
    if not isinstance(specs, (ast.Tuple, ast.List)):
        raise ValueError("Missing literal SPECS sequence")
    tools = []
    for call in specs.elts:
        if (
            not isinstance(call, ast.Call)
            or not isinstance(call.func, ast.Name)
            or call.func.id != "ToolSpec"
        ):
            raise ValueError("SPECS must contain ToolSpec calls")
        name, description = (ast.literal_eval(arg) for arg in call.args[:2])
        schema = call.args[2]
        if (
            not isinstance(schema, ast.Call)
            or not isinstance(schema.func, ast.Name)
            or schema.func.id != "_schema"
        ):
            raise ValueError("Tool schema must use _schema")
        tools.append(
            {
                "name": name,
                "description": description,
                "properties": _properties(schema.args[0], assignments),
                "required": ast.literal_eval(schema.args[1]) if len(schema.args) > 1 else [],
                "annotations": ast.literal_eval(call.args[4]) if len(call.args) > 4 else {},
            }
        )
    names = [tool["name"] for tool in tools]
    if len(names) != len(set(names)):
        raise ValueError("Duplicate tool names")
    return tools


def _cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def render(groups):
    lines = [
        "Generated by `tools/gen_mcp_docs.py` from `scenario/mcp/tools_*.py`.",
        "Do not edit this block by hand; run `make mcp-docs`. An asterisk marks a required argument.",
    ]
    for title, tools in groups:
        lines.extend(
            [
                "",
                f"### {title}",
                "",
                "| Tool | Description | Arguments | Notes |",
                "| --- | --- | --- | --- |",
            ]
        )
        for tool in tools:
            args = []
            for name, spec in tool["properties"].items():
                required = "*" if name in tool["required"] else ""
                argument = f"`{name}`{required}: {_cell(spec.get('type', 'value'))}"
                if "enum" in spec:
                    argument += f" ({_cell(spec['enum']) if isinstance(spec['enum'], list) else 'enum: see tools/list'})"
                if spec.get("description"):
                    argument += f"; {_cell(spec['description'])}"
                args.append(argument)
            description = tool["description"]
            notes = []
            if tool["annotations"].get("readOnlyHint"):
                notes.append("read-only annotation")
            if tool["annotations"].get("destructiveHint"):
                notes.append("destructive annotation")
            if re.search(r"\bGUI\b", description) or "Do not use in background mode" in description:
                notes.append("GUI required")
            if "spends the user's credits" in description:
                notes.append("spends credits")
            if "Disabled by default" in description:
                notes.append("Python preference gate; off by default")
            lines.append(
                f"| `{tool['name']}` | {_cell(description.splitlines()[0])} | {'<br>'.join(args) or 'none'} | {'; '.join(notes) or '-'} |"
            )
    return "\n".join(lines) + "\n"


def generated(root=ROOT):
    return render([(title, parse_specs(root / path)) for title, path in GROUPS])


def families(groups):
    """Sort tool names into FAMILIES: scene tools first, then Scenario tools by pattern."""
    (_, scene), (_, scenario) = groups
    members = {key: [] for key, *_ in FAMILIES}
    members["scene"] = [tool["name"] for tool in scene]
    for tool in scenario:
        key = next(
            (
                key
                for key, *_, pattern in reversed(FAMILIES)
                if pattern and re.search(pattern, tool["name"])
            ),
            "generate",
        )
        members[key].append(tool["name"])
    return members


def render_map(groups):
    """Return the guide's tool map: one focusable square per tool, grouped by family."""
    members = families(groups)
    lines = [
        "",
        "<!-- Generated by tools/gen_mcp_docs.py; run make mcp-docs instead of editing. -->",
        '<div class="tool-map">',
    ]
    for key, title, summary, _ in FAMILIES:
        if not members[key]:
            continue
        experimental = key in EXPERIMENTAL
        tag = ' <span class="tool-family-tag">experimental</span>' if experimental else ""
        lines.append(
            f'<div class="tool-family f-{key}{" wide experimental" if experimental else ""}">'
        )
        lines.append(
            f'<p class="tool-family-head"><b>{len(members[key])}</b> {html.escape(title)}{tag}</p>'
        )
        lines.append("<ul>")
        lines.extend(
            f'<li tabindex="0"><code>{html.escape(name)}</code></li>' for name in members[key]
        )
        lines.append("</ul>")
        lines.append(f'<p class="tool-family-note">{html.escape(summary)}</p>')
        lines.append("</div>")
    lines.extend(["</div>", "", ""])
    return "\n".join(lines)


def generated_map(root=ROOT):
    return render_map([(title, parse_specs(root / path)) for title, path in GROUPS])


def replace_block(document, block, start=START, end=END):
    if document.count(start) != 1 or document.count(end) != 1:
        raise ValueError(f"Document needs exactly one {start} block")
    if document.index(end) < document.index(start):
        raise ValueError(f"Generated block markers {start} and {end} are reversed")
    before, rest = document.split(start)
    _, after = rest.split(end)
    return before + start + "\n" + block + end + after


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    block = generated()
    if not (args.write or args.check):
        print(block, end="")
        return 0
    tool_map = generated_map()
    targets = (
        ("docs/MCP.md", block, START, END),
        ("docs/USER_GUIDE.md", tool_map, MAP_START, MAP_END),
        ("docs/USER_GUIDE.md", tool_map, INTRO_START, INTRO_END),
    )
    stale = False
    for relative, content, start, end in targets:
        path = ROOT / relative
        document = path.read_text(encoding="utf-8")
        updated = replace_block(document, content, start, end)
        if args.check:
            if document != updated:
                print(f"{relative} has a stale generated block; run make mcp-docs")
                stale = True
        else:
            path.write_text(updated, encoding="utf-8")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
